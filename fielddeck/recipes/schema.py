def _step_error(
    message: str, *, phase: str, index: int, kind: str | None = None, **details: Any
) -> RecipeError:
    where = f"{phase} step {index}"
    return RecipeError(
        f"{where}: {message}",
        details={"phase": phase, "step": index, "kind": kind, **details},
        preserved="the recipe was not compiled and nothing was run",
    )


def _validation_problems(exc: ValidationError) -> list[dict[str, str]]:
    return [
        {"field": ".".join(str(part) for part in err["loc"]) or "(step)", "problem": err["msg"]}
        for err in exc.errors()
    ]


def _build(model: type[Any], data: dict[str, Any], *, phase: str, index: int, kind: str) -> Any:
    try:
        return model.model_validate({**data, "source_index": index})
    except ValidationError as exc:
        problems = _validation_problems(exc)
        first = problems[0]
        raise _step_error(
            f"{first['field']}: {first['problem']}",
            phase=phase,
            index=index,
            kind=kind,
            errors=problems,
        ) from exc


def _parse_step(raw: Any, *, phase: str, index: int, depth: int) -> Step:
    if not isinstance(raw, dict):
        raise _step_error(
            f"expected a mapping, got {type(raw).__name__}",
            phase=phase,
            index=index,
        )
    keys = set(raw)
    if not keys:
        raise _step_error("is empty", phase=phase, index=index)

    # Key-form kinds first.  ``mark`` is checked before ``note`` so that
    # ``{mark: power-up, note: "..."}`` is one annotated mark, not two steps.
    if "assert" in keys:
        return _parse_assert(raw, phase=phase, index=index)
    if "wait" in keys:
        return _build(WaitStep, {"seconds": raw["wait"]}, phase=phase, index=index, kind="wait")
    if "mark" in keys:
        return _build(
            MarkStep,
            {"label": raw["mark"], "note": raw.get("note")},
            phase=phase,
            index=index,
            kind="mark",
        )
    if "note" in keys:
        return _build(NoteStep, {"text": raw["note"]}, phase=phase, index=index, kind="note")
    if "repeat" in keys:
        return _parse_repeat(raw["repeat"], phase=phase, index=index, depth=depth)
    if "action" in keys:
        return _parse_action(raw, phase=phase, index=index, depth=depth)

    raise _step_error(
        "has no 'action' and is not a wait/assert/mark/note/repeat step "
        f"(keys were: {', '.join(sorted(str(k) for k in keys))})",
        phase=phase,
        index=index,
        keys=sorted(str(k) for k in keys),
    )


def _parse_assert(raw: dict[str, Any], *, phase: str, index: int) -> AssertStep:
    body = raw["assert"]
    if isinstance(body, str):
        data = {"expression": body, "message": raw.get("message")}
    elif isinstance(body, dict):
        extra = set(body) - {"expression", "message"}
        if extra:
            raise _step_error(
                f"assert takes 'expression' and 'message'; got {', '.join(sorted(extra))}",
                phase=phase,
                index=index,
                kind="assert",
            )
        data = {"expression": body.get("expression"), "message": body.get("message")}
    else:
        raise _step_error(
            "assert takes an expression string or a mapping with 'expression'",
            phase=phase,
            index=index,
            kind="assert",
        )
    return _build(AssertStep, data, phase=phase, index=index, kind="assert")


def _parse_repeat(body: Any, *, phase: str, index: int, depth: int) -> RepeatStep:
    if depth >= MAX_REPEAT_DEPTH:
        raise _step_error(
            f"repeat is nested more than {MAX_REPEAT_DEPTH} deep",
            phase=phase,
            index=index,
            kind="repeat",
        )
    if not isinstance(body, dict):
        raise _step_error(
            "repeat takes a mapping with 'count' and 'steps'",
            phase=phase,
            index=index,
            kind="repeat",
        )
    extra = set(body) - {"count", "steps"}
    if extra:
        raise _step_error(
            f"repeat takes 'count' and 'steps'; got {', '.join(sorted(extra))}",
            phase=phase,
            index=index,
            kind="repeat",
        )
    nested = _parse_steps(
        body.get("steps"), phase=f"{phase}[repeat@{index}]", depth=depth + 1, required=True
    )
    return _build(
        RepeatStep,
        {"count": body.get("count"), "steps": nested},
        phase=phase,
        index=index,
        kind="repeat",
    )


def _parse_action(raw: dict[str, Any], *, phase: str, index: int, depth: int) -> Step:
    name = raw["action"]
    if not isinstance(name, str) or not name.strip():
        raise _step_error("'action' must name an action", phase=phase, index=index)
    name = name.strip()

    # The two conceptual step kinds that read naturally as actions.  Both
    # spellings appear in the specification's examples, and refusing one of
    # them would only make recipes harder to write, not safer.
    if name == "wait":
        _reject_unexpected(raw, {"action", "seconds"}, phase=phase, index=index, kind="wait")
        return _build(
            WaitStep, {"seconds": raw.get("seconds")}, phase=phase, index=index, kind="wait"
        )
    if name == "assert":
        _reject_unexpected(
            raw, {"action", "expression", "message"}, phase=phase, index=index, kind="assert"
        )
        return _build(
            AssertStep,
            {"expression": raw.get("expression"), "message": raw.get("message")},
            phase=phase,
            index=index,
            kind="assert",
        )
    if name == "repeat":
        return _parse_repeat(
            {"count": raw.get("count"), "steps": raw.get("steps")},
            phase=phase,
            index=index,
            depth=depth,
        )

    inline = {key: value for key, value in raw.items() if key not in RESERVED_STEP_KEYS}
    explicit = raw.get("params")
    if explicit is not None and inline:
        raise _step_error(
            "give parameters inline or under 'params:', not both "
            f"(inline: {', '.join(sorted(inline))})",
            phase=phase,
            index=index,
            kind="action",
        )
    params = explicit if explicit is not None else inline
    if not isinstance(params, dict) or any(not isinstance(key, str) for key in params):
        raise _step_error(
            "parameters must be a mapping with text keys",
            phase=phase,
            index=index,
            kind="action",
        )
    return _build(
        ActionStep,
        {
            "action": name,
            "params": params,
            "store": raw.get("store"),
            "timeout_s": raw.get("timeout_s"),
        },
        phase=phase,
        index=index,
        kind="action",
    )


def _reject_unexpected(
    raw: dict[str, Any], allowed: set[str], *, phase: str, index: int, kind: str
) -> None:
    extra = set(raw) - allowed
    if extra:
        raise _step_error(
            f"{kind} takes {', '.join(sorted(allowed - {'action'}))}; "
            f"got {', '.join(sorted(str(key) for key in extra))}",
            phase=phase,
            index=index,
            kind=kind,
        )


def _parse_steps(raw: Any, *, phase: str, depth: int = 0, required: bool = False) -> list[Step]:
    if raw is None:
        if required:
            raise RecipeError(
                f"{phase} has no steps",
                details={"phase": phase},
                preserved="the recipe was not compiled and nothing was run",
            )
        return []
    if not isinstance(raw, list):
        raise RecipeError(
            f"{phase} must be a list of steps, got {type(raw).__name__}",
            details={"phase": phase},
            preserved="the recipe was not compiled and nothing was run",
        )
    if len(raw) > MAX_STEPS_PER_PHASE:
        raise RecipeError(
            f"{phase} has {len(raw)} steps; the limit is {MAX_STEPS_PER_PHASE}",
            details={"phase": phase, "steps": len(raw)},
            preserved="the recipe was not compiled and nothing was run",
        )
    return [
        _parse_step(entry, phase=phase, index=index, depth=depth) for index, entry in enumerate(raw)
    ]


def parse_recipe(data: Any) -> Recipe:
    """Validate an already-decoded recipe document."""
    if not isinstance(data, dict):
        raise RecipeError(
            f"a recipe must be a YAML mapping, got {type(data).__name__}",
            preserved="nothing was run",
        )
    version = data.get("version", 1)
    if version not in SUPPORTED_VERSIONS:
        raise RecipeError(
            f"recipe format version {version!r} is not supported by this build "
            f"(supported: {', '.join(str(v) for v in sorted(SUPPORTED_VERSIONS))})",
            details={"version": version},
            preserved="nothing was run",
        )
    payload = dict(data)
    payload["steps"] = _parse_steps(payload.get("steps"), phase=str(RecipePhase.STEPS))
    payload["finally"] = _parse_steps(payload.pop("finally", None), phase=str(RecipePhase.FINALLY))
    payload.pop("finally_", None)
    try:
        return Recipe.model_validate(payload)
    except ValidationError as exc:
        problems = _validation_problems(exc)
        first = problems[0]
        raise RecipeError(
            f"recipe is invalid: {first['field']}: {first['problem']}",
            details={"errors": problems},
            preserved="nothing was run",
        ) from exc


def load_recipe_text(text: str, *, path: str | None = None) -> LoadedRecipe:
    """Parse recipe YAML.  ``safe_load`` only: no object construction."""
    raw = text.encode("utf-8")
    if len(raw) > MAX_RECIPE_BYTES:
        raise RecipeError(
            f"recipe is {len(raw)} bytes; the limit is {MAX_RECIPE_BYTES}",
            details={"path": path},
            preserved="nothing was read into the engine",
        )
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise RecipeError(
            f"{path or 'recipe'} is not valid YAML: {exc}",
            details={"path": path},
            preserved="nothing was run",
        ) from exc
    recipe = parse_recipe(data)
    return LoadedRecipe(
        recipe=recipe,
        source=RecipeSource(path=path, sha256=hashlib.sha256(raw).hexdigest(), size_bytes=len(raw)),
    )


def load_recipe_file(path: Path) -> LoadedRecipe:
    try:
        if path.stat().st_size > MAX_RECIPE_BYTES:
            raise RecipeError(
                f"{path} is larger than the {MAX_RECIPE_BYTES} byte recipe limit",
                details={"path": str(path)},
                preserved="the file was not read",
            )
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RecipeError(
            f"cannot read recipe {path}: {exc}",
            details={"path": str(path)},
            preserved="nothing was run",
        ) from exc
    except UnicodeDecodeError as exc:
        raise RecipeError(
            f"{path} is not UTF-8 text; recipes are YAML files",
            details={"path": str(path)},
            preserved="nothing was run",
        ) from exc
    return load_recipe_text(text, path=str(path))


