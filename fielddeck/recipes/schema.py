"""What a recipe file is allowed to say — and nothing more.

A recipe is YAML, which means it is the part of FieldDeck most likely to have
been written by someone who is not in the room: copied off a wiki, generated by
an assistant, committed by a contributor who has never seen your bench.  So the
parser is strict on purpose.  Unknown keys are refused rather than ignored,
because a silently dropped ``current_limit`` is a recipe that energises a DUT
with the previous setpoint still in place.  Every error names the phase and the
step index, because "invalid recipe" at 2am is not a diagnosis.

Shapes accepted for one step, all equivalent to the engine:

    - action: psu.set          # an action, parameters inline
      device: role:psu
      voltage: 24.0

    - action: psu.set          # the same, parameters grouped
      params: {device: role:psu, voltage: 24.0}

    - wait: 2                  # or:  {action: wait, seconds: 2}
    - assert: "can.frames > 0" # or:  {assert: {expression: ..., message: ...}}
    - mark: power-up           # lowered to the real session.mark action
    - note: "clip the probe"   # lowered to the real session.note action
    - repeat: {count: 3, steps: [...]}

Parameters are literals.  There is deliberately no templating or interpolation
into an action's parameters: it is what lets the compiler check every voltage in
the file against the effective limits *before* anything runs, with no runtime
value able to slip past.
"""

