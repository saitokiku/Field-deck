#: A recipe is configuration, not data.  Anything larger is a mistake or an
#: attempt to make the parser the interesting part of the program.
MAX_RECIPE_BYTES = 512 * 1024
#: Steps written in one phase, before ``repeat`` expansion.
MAX_STEPS_PER_PHASE = 500
#: How deeply ``repeat`` may nest.
MAX_REPEAT_DEPTH = 3
#: Recipe format versions this build understands.
SUPPORTED_VERSIONS = frozenset({1})

#: Keys on an action step that belong to the *engine*, not to the action.
#: Everything else on the step is a parameter, so an action gaining a new
#: parameter never needs a change here.
RESERVED_STEP_KEYS = frozenset({"action", "params", "store", "timeout_s"})

_YAML_SUFFIXES = (".yaml", ".yml")


class StepKind(StrEnum):
    ACTION = "action"
    WAIT = "wait"
    ASSERT = "assert"
    MARK = "mark"
    NOTE = "note"
    REPEAT = "repeat"


class RecipePhase(StrEnum):
    """``finally`` runs whatever happened to ``steps``."""

    STEPS = "steps"
    FINALLY = "finally"


# ---------------------------------------------------------------------------
# Steps
# ---------------------------------------------------------------------------


class _BaseStep(StrictModel):
    #: Index within the list it was written in, so an error can point at it.
    source_index: int = 0


class ActionStep(_BaseStep):
    kind: Literal[StepKind.ACTION] = StepKind.ACTION
    action: str = Field(min_length=1, max_length=120)
    params: dict[str, Any] = Field(default_factory=dict)
    #: Namespace the result is filed under for later assertions.  Defaults to
    #: the action's own prefix, so ``can.capture`` fills ``can``.
    store: str | None = Field(default=None, min_length=1, max_length=40)
    timeout_s: float | None = Field(default=None, gt=0, le=3600)

    @property
    def device(self) -> str | None:
        reference = self.params.get("device")
        return reference if isinstance(reference, str) else None

    @property
    def namespace(self) -> str:
        return self.store or self.action.split(".", 1)[0]


class WaitStep(_BaseStep):
    kind: Literal[StepKind.WAIT] = StepKind.WAIT
    seconds: float = Field(gt=0, le=3600)


class AssertStep(_BaseStep):
    kind: Literal[StepKind.ASSERT] = StepKind.ASSERT
    expression: str = Field(min_length=1, max_length=500)
    message: str | None = Field(default=None, max_length=500)


class MarkStep(_BaseStep):
    """A label on the unified timeline.  Lowered to ``session.mark``."""

    kind: Literal[StepKind.MARK] = StepKind.MARK
    label: str = Field(min_length=1, max_length=120)
    note: str | None = Field(default=None, max_length=500)


class NoteStep(_BaseStep):
    """Free text in the session record.  Lowered to ``session.note``."""

    kind: Literal[StepKind.NOTE] = StepKind.NOTE
    text: str = Field(min_length=1, max_length=2000)


class RepeatStep(_BaseStep):
    kind: Literal[StepKind.REPEAT] = StepKind.REPEAT
    count: int = Field(ge=1, le=1000)
    steps: list[Step]


Step = Annotated[
    ActionStep | WaitStep | AssertStep | MarkStep | NoteStep | RepeatStep,
    Field(discriminator="kind"),
]

RepeatStep.model_rebuild()


