def recipe_roots(paths: Paths | None = None) -> list[Path]:
    """Directories a recipe may be loaded from, most specific first.

    Recipes are read by the daemon, which runs as the instrument authority, so
    the set of directories it will read from is fixed rather than "whatever
    path the caller passed".  ``FIELDDECK_RECIPES_DIR`` is how an operator adds
    their own; the working-directory entry is what makes a git checkout work
    without installing anything.
    """
    paths = paths or default_paths()
    candidates: list[Path] = []
    override = os.environ.get("FIELDDECK_RECIPES_DIR")
    if override:
        candidates.extend(Path(part).expanduser() for part in override.split(os.pathsep) if part)
    candidates.append(paths.config_dir / "recipes")
    candidates.append(paths.state_dir / "recipes")
    candidates.append(Path.cwd() / "recipes")

    roots: list[Path] = []
    for candidate in candidates:
        try:
            resolved = candidate.resolve()
        except OSError:  # pragma: no cover - unreadable mount
            continue
        if resolved.is_dir() and resolved not in roots:
            roots.append(resolved)
    return roots


def list_recipe_files(roots: list[Path] | None = None, *, limit: int = 200) -> list[Path]:
    """Every recipe file in the search roots and their immediate subdirectories."""
    found: list[Path] = []
    for root in roots if roots is not None else recipe_roots():
        for suffix in _YAML_SUFFIXES:
            found.extend(sorted(root.glob(f"*{suffix}")))
            found.extend(sorted(root.glob(f"*/*{suffix}")))
        if len(found) >= limit:
            break
    unique: list[Path] = []
    for path in found:
        if path not in unique and path.is_file():
            unique.append(path)
    return unique[:limit]


def resolve_recipe_reference(reference: str, roots: list[Path] | None = None) -> Path:
    """Turn ``controller-smoke-test`` or a path into a file inside a known root.

    A recipe reference arrives from a CLI argument, an MCP call or another
    recipe, so it is treated as hostile: the resolved file must live inside one
    of the recipe roots.  ``../../etc/`` and a symlink pointing out of the tree
    are refused the same way.
    """
    if not reference or not reference.strip():
        raise RecipeError("no recipe was named", preserved="nothing was run")
    reference = reference.strip()
    search = roots if roots is not None else recipe_roots()
    if not search:
        raise RecipeError(
            "no recipe directory exists on this unit; create one or set FIELDDECK_RECIPES_DIR",
            details={"looked_in": [str(p) for p in recipe_roots()]},
            preserved="nothing was run",
        )

    candidates: list[Path] = []
    as_path = Path(reference).expanduser()
    if as_path.is_absolute():
        candidates.append(as_path)
    elif as_path.suffix in _YAML_SUFFIXES or "/" in reference:
        candidates.extend(root / as_path for root in search)
    else:
        for root in search:
            for suffix in _YAML_SUFFIXES:
                candidates.append(root / f"{reference}{suffix}")
                candidates.extend(sorted(root.glob(f"*/{reference}{suffix}")))

    for candidate in candidates:
        try:
            resolved = candidate.resolve()
        except OSError:  # pragma: no cover - unreadable mount
            continue
        if not resolved.is_file():
            continue
        if not any(resolved.is_relative_to(root) for root in search):
            raise RecipeError(
                f"{resolved} is outside the recipe directories; copy it into one of "
                f"{', '.join(str(root) for root in search)} first",
                details={"path": str(resolved), "roots": [str(root) for root in search]},
                preserved="the file was not read",
            )
        return resolved

    known = [path.stem for path in list_recipe_files(search)]
    raise RecipeError(
        f"no recipe named {reference!r} in {', '.join(str(root) for root in search)}",
        details={"reference": reference, "available": known},
        preserved="nothing was run",
    )
