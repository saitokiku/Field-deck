class DeviceRequirement(StrictModel):
    """One device the recipe cannot run without, named by role or by id."""

    role: DeviceRole | None = None
    id: str | None = None
    note: str | None = Field(default=None, max_length=200)

    @model_validator(mode="after")
    def _exactly_one(self) -> DeviceRequirement:
        if (self.role is None) == (self.id is None):
            raise ValueError("give exactly one of 'role:' or 'id:' for each required device")
        return self

    @property
    def reference(self) -> str:
        """How the registry will be asked for it."""
        return f"role:{self.role}" if self.role is not None else str(self.id)


class Requires(StrictModel):
    devices: list[DeviceRequirement] = Field(default_factory=list, max_length=32)

    @model_validator(mode="before")
    @classmethod
    def _accept_bare_references(cls, data: Any) -> Any:
        """``- role:psu`` and ``- can:can0`` are as clear as the mapping form."""
        if not isinstance(data, dict):
            return data
        devices = data.get("devices")
        if not isinstance(devices, list):
            return data
        converted: list[Any] = []
        for entry in devices:
            if isinstance(entry, str) and entry.startswith("role:"):
                converted.append({"role": entry.split(":", 1)[1]})
            elif isinstance(entry, str):
                converted.append({"id": entry})
            else:
                converted.append(entry)
        return {**data, "devices": converted}


class LimitBound(StrictModel):
    maximum: float | None = None
    minimum: float | None = None

    @model_validator(mode="after")
    def _at_least_one(self) -> LimitBound:
        if self.maximum is None and self.minimum is None:
            raise ValueError("a limit needs a maximum, a minimum, or both")
        return self


class RecipeLimits(StrictModel):
    """The envelope the recipe says it stays inside.

    These can only *tighten* what the deployment allows.  A recipe asking for
    more headroom than ``safety.yaml`` permits was written for a different
    bench, and the compiler refuses it rather than quietly clamping — clamping
    would run a test that is not the test the author described.
    """

    voltage_max: float | None = Field(default=None, ge=0)
    current_max: float | None = Field(default=None, ge=0)
    power_max: float | None = Field(default=None, ge=0)
    #: Anything the three shorthands do not cover, e.g. ``gpio.voltage``.
    quantities: dict[str, LimitBound] = Field(default_factory=dict, max_length=32)

    @model_validator(mode="before")
    @classmethod
    def _accept_both_spellings(cls, data: Any) -> Any:
        if not isinstance(data, dict):
            return data
        renamed = {"max_voltage": "voltage_max", "max_current": "current_max"}
        renamed["max_power"] = "power_max"
        out = dict(data)
        for old, new in renamed.items():
            if old in out:
                if new in out:
                    raise ValueError(f"give either {old} or {new}, not both")
                out[new] = out.pop(old)
        return out

    def as_limits(self) -> dict[str, SafetyLimit]:
        """The declared envelope as limits the enforcer understands."""
        limits: dict[str, SafetyLimit] = {}
        for quantity, maximum in (
            ("psu.voltage", self.voltage_max),
            ("psu.current", self.current_max),
            ("psu.power", self.power_max),
        ):
            if maximum is not None:
                limits[quantity] = SafetyLimit(quantity=quantity, maximum=maximum, minimum=0.0)
        for quantity, bound in self.quantities.items():
            declared = SafetyLimit(quantity=quantity, maximum=bound.maximum, minimum=bound.minimum)
            existing = limits.get(quantity)
            limits[quantity] = declared if existing is None else existing.intersect(declared)
        return limits

    def describe(self) -> dict[str, dict[str, float | None]]:
        return {
            quantity: {"minimum": limit.minimum, "maximum": limit.maximum}
            for quantity, limit in sorted(self.as_limits().items())
        }


class Recipe(StrictModel):
    """One parsed recipe file.  What it says, not yet what it will do."""

    model_config = ConfigDict(populate_by_name=True)

    version: int = 1
    name: str = Field(min_length=1, max_length=120)
    description: str | None = Field(default=None, max_length=2000)
    requires: Requires = Field(default_factory=Requires)
    limits: RecipeLimits = Field(default_factory=RecipeLimits)
    steps: list[Step] = Field(default_factory=list, max_length=MAX_STEPS_PER_PHASE)
    #: ``finally`` is a Python keyword, hence the trailing underscore.  YAML
    #: always spells it ``finally``.
    finally_: list[Step] = Field(
        default_factory=list, alias="finally", max_length=MAX_STEPS_PER_PHASE
    )

    def phase(self, phase: RecipePhase) -> list[Step]:
        return self.steps if phase is RecipePhase.STEPS else self.finally_


@dataclass(frozen=True, slots=True)
class RecipeSource:
    """Where a recipe came from, so a session report can prove which file ran."""

    path: str | None
    sha256: str
    size_bytes: int

    def describe(self) -> dict[str, Any]:
        return {"path": self.path, "sha256": self.sha256, "size_bytes": self.size_bytes}


@dataclass(frozen=True, slots=True)
class LoadedRecipe:
    recipe: Recipe
    source: RecipeSource


