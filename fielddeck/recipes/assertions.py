@dataclass(frozen=True, slots=True)
class AssertionOutcome:
    passed: bool
    value: Any
    #: What the operator needs to see: the expression with the values it read.
    detail: str
    referenced: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        return {
            "passed": self.passed,
            "value": self.value if isinstance(self.value, (bool, int, float, str)) else None,
            "detail": self.detail,
            "values": self.referenced,
        }


def evaluate_assertion(
    compiled: CompiledExpression, namespace: Mapping[str, Any]
) -> AssertionOutcome:
    """Evaluate one assertion and describe the result in operator terms.

    Raises :class:`RecipeError` when the expression cannot be evaluated at all
    (an unknown name, an impossible comparison).  A well-formed expression that
    is simply false comes back as ``passed=False`` — that is a test result, not
    an error.
    """
    value, trace = compiled.evaluate(namespace)
    passed = bool(value)
    if trace:
        read = ", ".join(f"{name}={_render(item)}" for name, item in sorted(trace.items()))
        detail = f"{compiled.source}  [{read}]"
    else:
        detail = compiled.source
    return AssertionOutcome(passed=passed, value=value, detail=detail, referenced=dict(trace))


def _render(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:g}"
    return repr(value) if isinstance(value, str) else str(value)
