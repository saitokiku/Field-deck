"""A deliberately small expression language for recipe assertions.

An ``assert`` step in a recipe file is untrusted input.  Recipes get shared on
wikis, pasted out of chat logs, committed by contributors and generated by
assistants; ``eval()`` would hand every one of those the whole Python runtime,
on a machine that is physically wired to a power supply and a CAN bus.  So
nothing here evaluates Python.  The expression is parsed with :mod:`ast` and
walked against an explicit allowlist of node types; anything unrecognised —
a call to something that is not one of seven arithmetic builtins, an import,
an f-string, a lambda, a walrus — is rejected before the recipe compiles, not
while the DUT is energised.

Two properties are worth stating plainly because the rest of the design leans
on them:

* **Attribute access is dictionary lookup, never** ``getattr``.  ``can.frames``
  means ``namespace["can"]["frames"]``.  There is no path from an expression to
  a Python object's attributes, so ``__class__``/``__globals__`` escapes are
  structurally impossible rather than blacklisted.
* **The namespace holds scalars.**  A step result's lists and payloads are
  bound to their *size* (see :func:`scalar_view`), because an assertion is
  about how many frames arrived and how many amps flowed, not about the bytes
  themselves — those are in the capture file, immutable, where they belong.
"""

from __future__ import annotations

import ast
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

from fielddeck.common.errors import RecipeError

__all__ = [
    "ALLOWED_FUNCTIONS",
    "LITERAL_NAMES",
    "MAX_EXPRESSION_CHARS",
    "AssertionOutcome",
    "CompiledExpression",
    "compile_expression",
    "evaluate_assertion",
    "namespace_entry",
    "scalar_view",
]

#: An assertion that needs more than this is a program, and a recipe step is
#: not the place to keep a program.
MAX_EXPRESSION_CHARS = 500
#: Ceiling on parsed nodes.  Bounds evaluation cost for a hostile file.
MAX_NODES = 200
#: Ceiling on nesting depth during evaluation, so recursion cannot blow the
#: interpreter stack from a YAML file.
MAX_DEPTH = 32
#: ``2 ** 10**9`` is a memory bomb with no exception to catch in time, so the
#: exponent must be a small literal.
MAX_POW_EXPONENT = 32
#: Guards ``min``/``max``/``any``/``all`` over literal sequences.
MAX_SEQUENCE_ITEMS = 64
#: Ceiling on the magnitude of any intermediate integer, in bits.
#:
#: The compile-time exponent limit bounds one ``**`` node but does not
#: compose: every exponent in ``(((9**32)**32)**32)`` is a legal small
#: literal, and the result is 9**32768. Nest a few more and the evaluation
#: never returns. Bounding the *result* is what actually closes it, and 4096
#: bits is far beyond anything a real assertion about a bus needs.
MAX_RESULT_BITS = 4096

#: Recipes are YAML, and a YAML author writes ``false``, not ``False``.  These
#: spellings are bound as literals so an assertion reads the way the file around
#: it does; the Python spellings are keywords and parse as constants already.
LITERAL_NAMES: dict[str, Any] = {"true": True, "false": False, "null": None}

#: The only callables an expression may reach.  Every one is pure, total on
#: the values the namespace can hold, and cheap.
ALLOWED_FUNCTIONS: dict[str, Callable[..., Any]] = {
    "len": len,
    "abs": abs,
    "min": min,
    "max": max,
    "round": round,
    "any": any,
    "all": all,
}

_ALLOWED_NODES: tuple[type[ast.AST], ...] = (
    ast.Expression,
    ast.BoolOp,
    ast.UnaryOp,
    ast.BinOp,
    ast.Compare,
    ast.Call,
    ast.Constant,
    ast.Name,
    ast.Attribute,
    ast.Subscript,
    ast.Load,
    ast.Tuple,
    ast.List,
    # operators
    ast.And,
    ast.Or,
    ast.Not,
    ast.USub,
    ast.UAdd,
    ast.Add,
    ast.Sub,
    ast.Mult,
    ast.Div,
    ast.FloorDiv,
    ast.Mod,
    ast.Pow,
    # comparisons
    ast.Eq,
    ast.NotEq,
    ast.Lt,
    ast.LtE,
    ast.Gt,
    ast.GtE,
    ast.In,
    ast.NotIn,
    ast.Is,
    ast.IsNot,
)

_ORDERING_OPS = (ast.Lt, ast.LtE, ast.Gt, ast.GtE)


def _fail(message: str, source: str, **details: Any) -> RecipeError:
    return RecipeError(
        message,
        details={"expression": source, **details},
        preserved="the assertion was not evaluated and no action was taken",
    )


# ---------------------------------------------------------------------------
# Compilation
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class CompiledExpression:
    """A parsed, allowlist-checked expression.

    Compiling is separated from evaluating on purpose: the recipe compiler
    checks every assertion in the file *before* the first action runs, so a
    malformed or malicious expression fails compilation rather than surfacing
    at step nine with an output enabled.
    """

    source: str
    #: Root namespace names the expression reads, e.g. ``("can", "psu")``.
    names: tuple[str, ...]
    tree: ast.Expression = field(repr=False)

    def evaluate(self, namespace: Mapping[str, Any]) -> tuple[Any, dict[str, Any]]:
        """Return ``(value, trace)``.  ``trace`` maps each dotted name that was
        read to the value it had, which is what makes a failure report useful."""
        trace: dict[str, Any] = {}
        value = _eval(self.tree.body, namespace, trace, 0, self.source)
        return value, trace


def compile_expression(source: str) -> CompiledExpression:
    """Parse and vet one assertion expression.  Raises :class:`RecipeError`."""
    text = source.strip()
    if not text:
        raise _fail("assertion expression is empty", source)
    if len(text) > MAX_EXPRESSION_CHARS:
        raise _fail(
            f"assertion expression is {len(text)} characters; the limit is "
            f"{MAX_EXPRESSION_CHARS}. Split it into several assert steps.",
            text[:120],
        )
    try:
        tree = ast.parse(text, mode="eval")
    except SyntaxError as exc:
        raise _fail(
            f"assertion is not a valid expression: {exc.msg}", text, offset=exc.offset
        ) from exc
    except (RecursionError, MemoryError, ValueError) as exc:
        # A pathologically nested expression can exhaust the parser itself.
        raise _fail(f"assertion could not be parsed: {exc}", text) from exc

    nodes = list(ast.walk(tree))
    if len(nodes) > MAX_NODES:
        raise _fail(
            f"assertion has {len(nodes)} parsed elements; the limit is {MAX_NODES}",
            text,
        )
    for node in nodes:
        _vet(node, text)

    called = {
        node.func.id
        for node in nodes
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
    }
    names = tuple(
        sorted(
            {node.id for node in nodes if isinstance(node, ast.Name)} - called - set(LITERAL_NAMES)
        )
    )
    return CompiledExpression(source=text, names=names, tree=tree)


def _vet(node: ast.AST, source: str) -> None:
    """Reject anything not on the allowlist, with the reason spelled out."""
    if not isinstance(node, _ALLOWED_NODES):
        raise _fail(
            f"{type(node).__name__} is not allowed in a recipe assertion. Assertions "
            "may only compare, combine and do arithmetic on step results.",
            source,
            node=type(node).__name__,
        )
    if isinstance(node, ast.Constant):
        if not (node.value is None or isinstance(node.value, (str, int, float, bool))):
            raise _fail(
                f"{type(node.value).__name__} literals are not allowed in an assertion",
                source,
            )
    elif isinstance(node, ast.Name):
        if node.id.startswith("_"):
            raise _fail(f"name {node.id!r} is not readable from an assertion", source)
    elif isinstance(node, ast.Attribute):
        if node.attr.startswith("_"):
            # Redundant given that attribute access is a dict lookup, but a
            # second lock on the door that must never open costs nothing.
            raise _fail(f"attribute {node.attr!r} is not readable from an assertion", source)
    elif isinstance(node, ast.Call):
        _vet_call(node, source)
    elif isinstance(node, ast.BinOp) and isinstance(node.op, ast.Pow):
        exponent = node.right
        if not (
            isinstance(exponent, ast.Constant)
            and isinstance(exponent.value, (int, float))
            and not isinstance(exponent.value, bool)
            and abs(exponent.value) <= MAX_POW_EXPONENT
        ):
            raise _fail(
                f"the exponent of ** must be a literal number no larger than {MAX_POW_EXPONENT}",
                source,
            )


def _vet_call(node: ast.Call, source: str) -> None:
    if not isinstance(node.func, ast.Name):
        raise _fail(
            "only the plain functions "
            f"{', '.join(sorted(ALLOWED_FUNCTIONS))} may be called in an assertion",
            source,
        )
    if node.func.id not in ALLOWED_FUNCTIONS:
        raise _fail(
            f"{node.func.id}() is not available in an assertion; allowed functions are "
            f"{', '.join(sorted(ALLOWED_FUNCTIONS))}",
            source,
            function=node.func.id,
        )
    if node.keywords:
        raise _fail(f"{node.func.id}() takes no keyword arguments in an assertion", source)
    if any(isinstance(arg, ast.Starred) for arg in node.args):
        raise _fail(f"{node.func.id}() may not be called with *args in an assertion", source)
    if len(node.args) > 8:
        raise _fail(f"{node.func.id}() takes at most 8 arguments in an assertion", source)


