class TestSourceProvenance:
    def test_the_source_hash_proves_which_file_ran(self) -> None:
        loaded = load_recipe_text(MINIMAL, path="minimal.yaml")
        assert loaded.source.path == "minimal.yaml"
        assert len(loaded.source.sha256) == 64
        assert loaded.source.size_bytes == len(MINIMAL.encode("utf-8"))

    def test_an_edited_recipe_hashes_differently(self) -> None:
        first = load_recipe_text(MINIMAL).source.sha256
        second = load_recipe_text(MINIMAL.replace("system.status", "device.list")).source.sha256
        assert first != second


class TestFileResolution:
    @pytest.fixture
    def recipe_dir(self, paths: Paths, monkeypatch: pytest.MonkeyPatch) -> Path:
        root = paths.config_dir / "recipes"
        (root / "nested").mkdir(parents=True)
        (root / "smoke.yaml").write_text(MINIMAL, encoding="utf-8")
        (root / "nested" / "deep.yml").write_text(MINIMAL, encoding="utf-8")
        monkeypatch.setenv("FIELDDECK_RECIPES_DIR", str(root))
        # ``./recipes`` is one of the search roots, and running pytest from the
        # repository would otherwise pull in the shipped examples.
        monkeypatch.chdir(paths.home)
        return root

    def test_a_bare_name_resolves_inside_a_known_root(self, recipe_dir: Path) -> None:
        assert resolve_recipe_reference("smoke") == recipe_dir / "smoke.yaml"

    def test_an_immediate_subdirectory_is_searched_too(self, recipe_dir: Path) -> None:
        assert resolve_recipe_reference("deep") == recipe_dir / "nested" / "deep.yml"

    def test_listing_finds_every_recipe_file(self, recipe_dir: Path) -> None:
        found = {path.name for path in list_recipe_files()}
        assert found == {"smoke.yaml", "deep.yml"}

    def test_a_path_outside_the_roots_is_refused(
        self, recipe_dir: Path, tmp_path: Path
    ) -> None:
        """The reference arrives from a CLI argument or an MCP call, so it is
        treated as hostile."""
        outside = tmp_path / "elsewhere.yaml"
        outside.write_text(MINIMAL, encoding="utf-8")

        with pytest.raises(RecipeError) as caught:
            resolve_recipe_reference(str(outside))
        assert caught.value.preserved == "the file was not read"

    def test_traversal_out_of_a_root_is_refused(self, recipe_dir: Path) -> None:
        with pytest.raises(RecipeError):
            resolve_recipe_reference("../../../etc/passwd")

    def test_a_symlink_pointing_out_of_the_tree_is_refused(
        self, recipe_dir: Path, tmp_path: Path
    ) -> None:
        outside = tmp_path / "outside.yaml"
        outside.write_text(MINIMAL, encoding="utf-8")
        (recipe_dir / "sneaky.yaml").symlink_to(outside)

        with pytest.raises(RecipeError, match="outside the recipe directories"):
            resolve_recipe_reference("sneaky")

    def test_an_unknown_name_lists_what_is_available(self, recipe_dir: Path) -> None:
        with pytest.raises(RecipeError) as caught:
            resolve_recipe_reference("does-not-exist")
        assert set(caught.value.details["available"]) == {"smoke", "deep"}

    def test_an_empty_reference_is_refused(self, recipe_dir: Path) -> None:
        with pytest.raises(RecipeError, match="no recipe was named"):
            resolve_recipe_reference("   ")

    def test_the_roots_are_a_fixed_set_not_whatever_was_passed(
        self, recipe_dir: Path, paths: Paths, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("FIELDDECK_RECIPES_DIR", raising=False)
        monkeypatch.chdir(paths.home)
        roots = recipe_roots(paths)
        assert all(root.is_dir() for root in roots)
        assert (paths.config_dir / "recipes").resolve() in roots

    def test_several_roots_may_be_given_at_once(
        self, recipe_dir: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        other = tmp_path / "more-recipes"
        other.mkdir()
        (other / "extra.yaml").write_text(MINIMAL, encoding="utf-8")
        monkeypatch.setenv("FIELDDECK_RECIPES_DIR", os.pathsep.join([str(recipe_dir), str(other)]))

        assert resolve_recipe_reference("extra") == other / "extra.yaml"
        assert {path.stem for path in list_recipe_files()} == {"smoke", "deep", "extra"}


class TestFixtureRecipes:
    """The checked-in fixtures must stay parseable, since other tests use them."""

    @pytest.mark.parametrize(
        "name", ["passive-listen", "power-up", "over-limit", "malicious-assert"]
    )
    def test_the_fixture_recipes_parse(self, fixtures_dir: Path, name: str) -> None:
        loaded = load_recipe_file(fixtures_dir / "recipes" / f"{name}.yaml")
        assert loaded.recipe.name == name
        assert loaded.source.path.endswith(f"{name}.yaml")

    def test_the_broken_fixture_is_refused(self, fixtures_dir: Path) -> None:
        with pytest.raises(RecipeError):
            load_recipe_file(fixtures_dir / "recipes" / "unknown-key.yaml")

    def test_a_missing_file_is_reported_rather_than_crashing(self, tmp_path: Path) -> None:
        with pytest.raises(RecipeError) as caught:
            load_recipe_file(tmp_path / "nope.yaml")
        assert caught.value.preserved == "nothing was run"

    def test_a_binary_file_is_not_a_recipe(self, tmp_path: Path) -> None:
        target = tmp_path / "firmware.yaml"
        target.write_bytes(b"\x7fELF\x02\x01\x01\x00\xff\xfe")
        with pytest.raises(RecipeError):
            load_recipe_file(target)


class TestPhaseModel:
    def test_an_action_step_reports_no_device_when_it_names_none(self) -> None:
        step = parse("version: 1\nname: n\nsteps:\n  - action: system.status\n").steps[0]
        assert isinstance(step, ActionStep)
        assert step.device is None

    def test_assert_steps_carry_their_message_for_the_failure_report(self) -> None:
        step = parse(
            'version: 1\nname: n\nsteps:\n  - assert:\n      expression: "1 == 1"\n'
            "      message: the rail did not come up\n"
        ).steps[0]
        assert isinstance(step, AssertStep)
        assert step.message == "the rail did not come up"

    def test_note_steps_keep_their_text_verbatim(self) -> None:
        step = parse("version: 1\nname: n\nsteps:\n  - note: |\n      two\n      lines\n").steps[0]
        assert isinstance(step, NoteStep)
        assert step.text == "two\nlines\n"
