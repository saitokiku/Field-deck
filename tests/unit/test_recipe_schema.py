class TestRefusals:
    def test_an_unknown_top_level_key_is_refused(self) -> None:
        with pytest.raises(RecipeError) as caught:
            parse("version: 1\nname: n\nstepz:\n  - wait: 1\n")
        assert "stepz" in str(caught.value)

    def test_an_unknown_step_kind_lists_the_keys_it_saw(self) -> None:
        with pytest.raises(RecipeError) as caught:
            parse("version: 1\nname: n\nsteps:\n  - device: role:psu\n    voltage: 24\n")
        assert "no 'action'" in str(caught.value)
        assert caught.value.details["keys"] == ["device", "voltage"]

    def test_an_error_names_the_phase_and_the_index(self) -> None:
        """"Invalid recipe" is not a diagnosis; "finally step 1" is."""
        with pytest.raises(RecipeError) as caught:
            parse("version: 1\nname: n\nsteps:\n  - wait: 1\nfinally:\n  - wait: 1\n  - {}\n")
        assert caught.value.details["phase"] == "finally"
        assert caught.value.details["step"] == 1

    def test_an_unsupported_version_is_refused_with_the_supported_set(self) -> None:
        with pytest.raises(RecipeError) as caught:
            parse("version: 99\nname: n\nsteps: []\n")
        assert caught.value.details["version"] == 99
        assert "supported: 1" in str(caught.value)

    def test_a_recipe_must_be_a_mapping(self) -> None:
        with pytest.raises(RecipeError, match="must be a YAML mapping"):
            parse("- just\n- a\n- list\n")

    def test_invalid_yaml_is_refused_with_its_path(self) -> None:
        with pytest.raises(RecipeError) as caught:
            load_recipe_text("steps: [unclosed\n", path="broken.yaml")
        assert "not valid YAML" in str(caught.value)
        assert caught.value.details["path"] == "broken.yaml"

    def test_an_over_sized_recipe_is_refused_before_it_is_parsed(self) -> None:
        """A recipe is configuration, not data."""
        with pytest.raises(RecipeError) as caught:
            load_recipe_text("# " + "x" * MAX_RECIPE_BYTES)
        assert caught.value.preserved == "nothing was read into the engine"

    def test_assert_takes_only_an_expression_and_a_message(self) -> None:
        with pytest.raises(RecipeError, match="assert takes"):
            parse(
                "version: 1\nname: n\nsteps:\n"
                '  - assert:\n      expression: "1 == 1"\n      retry: 3\n'
            )

    def test_repeat_cannot_nest_forever(self) -> None:
        body = "  - repeat:\n      count: 2\n      steps:\n"
        text = "version: 1\nname: n\nsteps:\n"
        indent = "  "
        for depth in range(MAX_REPEAT_DEPTH + 1):
            text += indent * depth + body.replace("\n  ", "\n" + indent * depth + "  ")
        text += indent * (MAX_REPEAT_DEPTH + 1) + "    - wait: 1\n"
        with pytest.raises(RecipeError):
            parse(text)

    def test_a_step_that_is_not_a_mapping_is_refused(self) -> None:
        with pytest.raises(RecipeError, match="expected a mapping"):
            parse("version: 1\nname: n\nsteps:\n  - just a string\n")

    def test_an_empty_step_is_refused(self) -> None:
        with pytest.raises(RecipeError, match="is empty"):
            parse("version: 1\nname: n\nsteps:\n  - {}\n")

    def test_a_recipe_needs_a_name(self) -> None:
        with pytest.raises(RecipeError):
            parse("version: 1\nsteps:\n  - wait: 1\n")


