class TestStepForms:
    def test_parameters_may_be_inline_or_grouped(self) -> None:
        """Both spellings appear in the documentation; both mean the same."""
        inline = parse(
            "version: 1\nname: n\nsteps:\n"
            "  - action: psu.set\n    device: role:psu\n    voltage: 24.0\n"
        ).steps[0]
        grouped = parse(
            "version: 1\nname: n\nsteps:\n"
            "  - action: psu.set\n    params: {device: role:psu, voltage: 24.0}\n"
        ).steps[0]

        assert isinstance(inline, ActionStep) and isinstance(grouped, ActionStep)
        assert inline.params == grouped.params == {"device": "role:psu", "voltage": 24.0}
        assert inline.device == "role:psu"

    def test_engine_keys_are_not_passed_to_the_action(self) -> None:
        step = parse(
            "version: 1\nname: n\nsteps:\n"
            "  - action: can.capture\n    device: sim:can:can0\n"
            "    store: bus\n    timeout_s: 30\n    duration_s: 2\n"
        ).steps[0]
        assert isinstance(step, ActionStep)
        assert step.params == {"device": "sim:can:can0", "duration_s": 2}
        assert step.store == "bus"
        assert step.timeout_s == 30

    def test_the_result_namespace_defaults_to_the_action_prefix(self) -> None:
        step = parse("version: 1\nname: n\nsteps:\n  - action: can.capture\n").steps[0]
        assert isinstance(step, ActionStep)
        assert step.namespace == "can"

    @pytest.mark.parametrize(
        ("text", "kind", "check"),
        [
            ("  - wait: 2\n", StepKind.WAIT, lambda s: s.seconds == 2),
            (
                "  - action: wait\n    seconds: 2\n",
                StepKind.WAIT,
                lambda s: s.seconds == 2,
            ),
            (
                '  - assert: "can.frames > 0"\n',
                StepKind.ASSERT,
                lambda s: s.expression == "can.frames > 0",
            ),
            (
                '  - assert:\n      expression: "can.frames > 0"\n      message: nothing arrived\n',
                StepKind.ASSERT,
                lambda s: s.message == "nothing arrived",
            ),
            ("  - mark: power-up\n", StepKind.MARK, lambda s: s.label == "power-up"),
            ("  - note: clip the probe\n", StepKind.NOTE, lambda s: s.text == "clip the probe"),
        ],
    )
    def test_every_documented_shorthand_parses(self, text: str, kind: StepKind, check) -> None:
        step = parse(f"version: 1\nname: n\nsteps:\n{text}").steps[0]
        assert step.kind is kind
        assert check(step)

    def test_a_mark_with_a_note_is_one_annotated_mark(self) -> None:
        """Not two steps: ``mark`` is checked before ``note`` for exactly this."""
        step = parse(
            "version: 1\nname: n\nsteps:\n  - mark: power-up\n    note: probe on TP4\n"
        ).steps[0]
        assert isinstance(step, MarkStep)
        assert step.note == "probe on TP4"

    def test_repeat_expands_nothing_at_parse_time_but_keeps_its_body(self) -> None:
        step = parse(
            "version: 1\nname: n\nsteps:\n"
            "  - repeat:\n      count: 3\n      steps:\n        - wait: 1\n"
        ).steps[0]
        assert isinstance(step, RepeatStep)
        assert step.count == 3
        assert isinstance(step.steps[0], WaitStep)

    def test_finally_is_spelled_the_yaml_way(self) -> None:
        recipe = parse(
            "version: 1\nname: n\nsteps:\n  - wait: 1\nfinally:\n  - mark: done\n"
        )
        assert isinstance(recipe.finally_[0], MarkStep)
        assert recipe.phase(RecipePhase.FINALLY) == recipe.finally_
        assert recipe.phase(RecipePhase.STEPS) == recipe.steps

    def test_steps_remember_where_they_were_written(self) -> None:
        recipe = parse("version: 1\nname: n\nsteps:\n  - wait: 1\n  - wait: 2\n  - wait: 3\n")
        assert [step.source_index for step in recipe.steps] == [0, 1, 2]


