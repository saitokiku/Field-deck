class TestRequires:
    def test_devices_may_be_named_by_role_or_by_id(self) -> None:
        recipe = parse(
            "version: 1\nname: n\nrequires:\n  devices:\n"
            "    - role: psu\n    - id: sim:can:can0\n"
            "steps:\n  - wait: 1\n"
        )
        assert recipe.requires.devices[0].role is DeviceRole.PSU
        assert recipe.requires.devices[0].reference == "role:psu"
        assert recipe.requires.devices[1].reference == "sim:can:can0"

    def test_a_bare_string_is_as_clear_as_the_mapping_form(self) -> None:
        recipe = parse(
            "version: 1\nname: n\nrequires:\n  devices: [role:psu, sim:can:can0]\n"
            "steps:\n  - wait: 1\n"
        )
        assert [device.reference for device in recipe.requires.devices] == [
            "role:psu",
            "sim:can:can0",
        ]

    def test_a_device_needs_exactly_one_of_role_or_id(self) -> None:
        with pytest.raises(RecipeError, match="exactly one"):
            parse(
                "version: 1\nname: n\nrequires:\n  devices:\n"
                "    - {role: psu, id: sim:visa:sim-psu-0}\n"
                "steps:\n  - wait: 1\n"
            )

    def test_an_unknown_role_is_refused(self) -> None:
        with pytest.raises(RecipeError):
            parse(
                "version: 1\nname: n\nrequires:\n  devices:\n    - role: teleporter\n"
                "steps:\n  - wait: 1\n"
            )


class TestLimits:
    def test_the_declared_envelope_becomes_real_limits(self) -> None:
        recipe = parse(
            "version: 1\nname: n\nlimits:\n"
            "  voltage_max: 12.0\n  current_max: 1.0\n  power_max: 10.0\n"
            "steps:\n  - wait: 1\n"
        )
        limits = recipe.limits.as_limits()
        assert limits["psu.voltage"].maximum == 12.0
        assert limits["psu.current"].maximum == 1.0
        assert limits["psu.power"].maximum == 10.0
        # A declared ceiling implies a floor of zero, not an unbounded negative.
        assert limits["psu.voltage"].minimum == 0.0

    def test_both_spellings_of_the_shorthands_are_accepted(self) -> None:
        assert (
            parse(
                "version: 1\nname: n\nlimits:\n  max_voltage: 12.0\nsteps:\n  - wait: 1\n"
            ).limits.voltage_max
            == 12.0
        )

    def test_giving_both_spellings_at_once_is_refused(self) -> None:
        with pytest.raises(RecipeError):
            parse(
                "version: 1\nname: n\nlimits:\n  max_voltage: 12.0\n  voltage_max: 24.0\n"
                "steps:\n  - wait: 1\n"
            )

    def test_an_arbitrary_quantity_can_be_bounded(self) -> None:
        recipe = parse(
            "version: 1\nname: n\nlimits:\n"
            "  quantities:\n    gpio.voltage: {maximum: 3.3}\n"
            "steps:\n  - wait: 1\n"
        )
        assert recipe.limits.as_limits()["gpio.voltage"].maximum == 3.3

    def test_a_limit_with_neither_bound_is_meaningless_and_refused(self) -> None:
        with pytest.raises(RecipeError):
            parse(
                "version: 1\nname: n\nlimits:\n  quantities:\n    gpio.voltage: {}\n"
                "steps:\n  - wait: 1\n"
            )


