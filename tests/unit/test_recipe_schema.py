"""The recipe parser, which is the most exposed input surface FieldDeck has.

A recipe is YAML written by someone who is probably not in the room: copied off
a wiki, generated by an assistant, committed by a contributor who has never
seen this bench.  So the parser is strict on purpose — an unknown key is a
refusal, not a shrug.  A silently dropped ``current_limit`` is a recipe that
energises a DUT with whatever setpoint happened to be left over.

The other thing these tests pin is the error's *usefulness*: every refusal has
to name the phase and the step index, because "invalid recipe" at 2am is not a
diagnosis.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from fielddeck.common.errors import RecipeError
from fielddeck.common.models import DeviceRole
from fielddeck.common.paths import Paths
from fielddeck.recipes.schema import (
    MAX_RECIPE_BYTES,
    MAX_REPEAT_DEPTH,
    ActionStep,
    AssertStep,
    MarkStep,
    NoteStep,
    RecipePhase,
    RepeatStep,
    StepKind,
    WaitStep,
    list_recipe_files,
    load_recipe_file,
    load_recipe_text,
    recipe_roots,
    resolve_recipe_reference,
)

MINIMAL = """
version: 1
name: minimal
steps:
  - action: system.status
"""


def parse(text: str):
    return load_recipe_text(text, path="test.yaml").recipe


