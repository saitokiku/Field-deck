"""The recipe expression evaluator, mostly from the attacker's side.

An ``assert`` step is untrusted input.  Recipes get shared on wikis, pasted out
of chat logs, committed by contributors and generated by assistants, and they
run on a machine physically wired to a power supply and a CAN bus.  ``eval()``
would hand every one of those the whole Python runtime.

Two structural properties do the heavy lifting, and both are tested here rather
than assumed:

* **Attribute access is a dictionary lookup, never ``getattr``.**  ``can.frames``
  means ``namespace["can"]["frames"]``.  There is no path from an expression to
  a Python object, so ``__class__`` escapes are impossible rather than
  blacklisted — the blacklist is belt and braces.
* **The namespace holds scalars.**  A frame list binds to its length, because
  an assertion is about how many frames arrived, not about the bytes; the bytes
  are in the capture file, immutable, where they belong.
"""

from __future__ import annotations

from typing import Any

import pytest

from fielddeck.common.errors import RecipeError
from fielddeck.recipes.assertions import (
    ALLOWED_FUNCTIONS,
    MAX_EXPRESSION_CHARS,
    compile_expression,
    evaluate_assertion,
    namespace_entry,
    scalar_view,
)

NAMESPACE: dict[str, Any] = {
    "can": {"frames": 12, "count": 12, "errors": 0, "nested": {"depth": 1}},
    "psu": {"voltage": 24.0, "current": 0.42, "output": True, "name": "psu-a"},
    "serial": {"bytes": 2491, "chunks": 302},
}


def run(expression: str, namespace: dict[str, Any] | None = None):
    return evaluate_assertion(compile_expression(expression), namespace or NAMESPACE)


