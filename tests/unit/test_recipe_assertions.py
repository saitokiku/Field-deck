class TestRejectsMaliciousInput:
    @pytest.mark.parametrize(
        "expression",
        [
            '__import__("os").system("id")',
            'open("/etc/passwd").read()',
            "(1).__class__.__bases__",
            "psu.__class__",
            "psu.__dict__",
            "can.__getitem__",
            "().__class__.__mro__[1].__subclasses__()",
            "globals()",
            "locals()",
            "eval('1')",
            "exec('x=1')",
            "compile('1', '', 'eval')",
            "getattr(psu, 'voltage')",
            "vars()",
            "dir()",
            "input()",
            "print(psu.voltage)",
            "help()",
            "breakpoint()",
        ],
    )
    def test_escapes_and_side_effects_are_refused_at_compile_time(
        self, expression: str
    ) -> None:
        """Refused before the recipe runs, not while the DUT is energised."""
        with pytest.raises(RecipeError) as caught:
            compile_expression(expression)
        assert caught.value.preserved == (
            "the assertion was not evaluated and no action was taken"
        )

    @pytest.mark.parametrize(
        "expression",
        [
            "lambda: 1",
            "[x for x in range(3)]",
            "{k: 1 for k in range(3)}",
            '{"a": 1}',
            "f'{psu.voltage}'",
            "(y := 3)",
            "1 if true else 2",
            "yield 1",
            "await x",
            "psu.voltage = 60",
            "import os",
            "del psu",
        ],
    )
    def test_anything_that_is_not_a_comparison_is_refused(self, expression: str) -> None:
        """Assertions may compare, combine and do arithmetic.  Nothing else."""
        with pytest.raises(RecipeError):
            compile_expression(expression)

    def test_only_the_seven_arithmetic_builtins_are_reachable(self) -> None:
        assert set(ALLOWED_FUNCTIONS) == {"len", "abs", "min", "max", "round", "any", "all"}
        for name in ALLOWED_FUNCTIONS:
            assert compile_expression(f"{name}([1, 2]) == {name}([1, 2])")

    def test_an_attribute_lookup_never_reaches_a_python_object(self) -> None:
        """The structural guarantee, stated as a test.

        ``psu`` is a plain dict in the namespace.  If attribute access were
        ``getattr`` this would return a bound method; instead it is a missing
        key, and the error says which keys exist.
        """
        with pytest.raises(RecipeError) as caught:
            run("psu.keys")
        assert "was not in the step result" in str(caught.value)


class TestResourceBombs:
    def test_a_huge_exponent_is_refused_at_compile_time(self) -> None:
        """``2 ** 10**9`` is a memory bomb with no exception to catch in time."""
        with pytest.raises(RecipeError, match="exponent"):
            compile_expression("2 ** 10**9")

    def test_nested_small_exponents_are_caught_by_the_result_bound(self) -> None:
        """Every exponent here is a legal small literal; the result is not."""
        with pytest.raises(RecipeError, match="bit number"):
            run("(((9**32)**32)**32)**32 > 0")

    def test_string_multiplication_is_not_arithmetic(self) -> None:
        with pytest.raises(RecipeError, match="needs numbers"):
            run('"a" * 10**9 == ""')

    def test_an_over_long_expression_is_refused_with_advice(self) -> None:
        with pytest.raises(RecipeError, match="Split it into several assert steps"):
            compile_expression("1 + " * (MAX_EXPRESSION_CHARS // 2) + "1")

    def test_a_deeply_nested_expression_is_refused_before_the_stack_is(self) -> None:
        """Recursion in the evaluator is bounded, so a YAML file cannot blow
        the interpreter stack."""
        expression = "len(" * 40 + "[1]" + ")" * 40
        with pytest.raises(RecipeError, match="nested too deeply"):
            evaluate_assertion(compile_expression(expression), {})

    def test_redundant_parentheses_are_not_nesting(self) -> None:
        """Grouping produces no AST nodes, so it is neither a bomb nor a
        problem — worth pinning so the depth guard is not "fixed" to reject it."""
        assert evaluate_assertion(compile_expression("(" * 60 + "1" + ")" * 60), {}).value == 1

    def test_an_empty_expression_is_refused(self) -> None:
        with pytest.raises(RecipeError, match="empty"):
            compile_expression("   ")


