class TestScalarView:
    def test_numbers_text_and_booleans_pass_through_untouched(self) -> None:
        """A voltage is never rounded or coerced on its way to an assertion."""
        for value in (24.000001, -3, "CV", True, False, None):
            assert scalar_view(value) == value

    @pytest.mark.parametrize(
        ("value", "expected"),
        [
            ([1, 2, 3], 3),
            ((1, 2), 2),
            (b"\x00\x01\x02", 3),
            (bytearray(5), 5),
            (memoryview(b"abcd"), 4),
        ],
    )
    def test_anything_with_a_size_binds_to_that_size(self, value: Any, expected: int) -> None:
        assert scalar_view(value) == expected

    def test_nested_results_are_projected_to_a_bounded_depth(self) -> None:
        deep = {"a": {"b": {"c": {"d": {"e": 1}}}}}
        assert scalar_view(deep) == {"a": {"b": {"c": 1}}}

    def test_an_opaque_object_reads_as_absent_rather_than_as_text(self) -> None:
        """A stray driver object has no honest scalar projection, and a
        misleading string would be worse than nothing."""

        class Driver:
            pass

        assert scalar_view(Driver()) is None

    def test_a_namespace_entry_hides_private_keys(self) -> None:
        entry = namespace_entry({"frames": [1, 2, 3], "_internal": 1, "count": 3})
        assert entry == {"frames": 3, "count": 3}

    def test_a_namespace_entry_is_bounded(self) -> None:
        entry = namespace_entry({f"k{index}": index for index in range(1000)}, max_keys=10)
        assert len(entry) == 10

    def test_a_frame_list_reads_as_its_length_which_is_what_recipes_ask(self) -> None:
        outcome = evaluate_assertion(
            compile_expression("can.frames > 0"),
            {"can": namespace_entry({"frames": [{"id": 1}, {"id": 2}]})},
        )
        assert outcome.passed is True
        assert outcome.referenced == {"can.frames": 2}
