class TestEverydayExpressions:
    @pytest.mark.parametrize(
        ("expression", "expected"),
        [
            ("can.frames > 0", True),
            ("can.frames > 100", False),
            ("psu.voltage == 24.0", True),
            ("psu.current > 0.05 and psu.current < 1.0", True),
            ("psu.output", True),
            ("not psu.output", False),
            ("psu.name == 'psu-a'", True),
            ("serial.bytes > 0 and serial.chunks > 1", True),
            ("can.errors == 0", True),
            ("can.frames in [11, 12, 13]", True),
            ("abs(psu.voltage - 24.0) < 0.5", True),
            ("round(psu.current, 1) == 0.4", True),
            ("min(can.frames, 100) == 12", True),
            ("can['frames'] == 12", True),
            ("can.nested.depth == 1", True),
        ],
    )
    def test_ordinary_assertions_evaluate(self, expression: str, expected: bool) -> None:
        assert run(expression).passed is expected

    def test_yaml_spellings_of_the_literals_are_accepted(self) -> None:
        """A recipe author writes ``false``, not ``False``; the file is YAML."""
        assert run("true and not false").passed is True
        assert run("null == null").passed is True

    def test_a_failing_assertion_is_a_result_not_an_error(self) -> None:
        outcome = run("psu.current > 99.0")
        assert outcome.passed is False
        assert outcome.detail == "psu.current > 99.0  [psu.current=0.42]"

    def test_the_detail_shows_every_value_that_was_read(self) -> None:
        """What the operator needs at 2am: the expression and its inputs."""
        outcome = run("psu.voltage > 12 and can.frames > 0")
        assert "psu.voltage=24" in outcome.detail
        assert "can.frames=12" in outcome.detail
        assert outcome.referenced == {"psu.voltage": 24.0, "can.frames": 12}

    def test_the_compiled_expression_reports_the_names_it_needs(self) -> None:
        """Which is how the compiler knows an assertion refers to a step that
        has not run yet."""
        compiled = compile_expression("can.frames > 0 and psu.voltage < 30")
        assert compiled.names == ("can", "psu")
        assert "len" not in compile_expression("len([1,2]) == 2").names


class TestEvaluationErrors:
    def test_an_unknown_namespace_lists_what_is_available(self) -> None:
        with pytest.raises(RecipeError) as caught:
            run("nope.thing > 1")
        assert "no step has produced 'nope' yet" in str(caught.value)
        assert "can, psu, serial" in str(caught.value)

    def test_a_missing_key_lists_the_keys_that_exist(self) -> None:
        with pytest.raises(RecipeError) as caught:
            run("can.voltage > 1")
        assert "was not in the step result" in str(caught.value)
        assert "frames" in str(caught.value)

    def test_ordering_a_number_against_text_is_refused(self) -> None:
        """Python would happily compare in some versions and explode in others;
        an instrument should just say what went wrong."""
        with pytest.raises(RecipeError, match="cannot order"):
            run("psu.voltage > 'x'")

    def test_division_by_zero_is_reported_as_an_assertion_problem(self) -> None:
        with pytest.raises(RecipeError):
            run("psu.voltage / can.errors > 1")


